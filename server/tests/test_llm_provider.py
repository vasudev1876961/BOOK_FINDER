from unittest.mock import MagicMock, patch

import httpx

from app.core.config import settings
from app.services.ai.llm_provider import (
    MockLlmProvider,
    OllamaLlmProvider,
    get_llm_provider,
)


def test_mock_llm_provider_summary():
    provider = MockLlmProvider()
    response = provider.generate_text("Summarize Atomic Habits")
    assert "elevator pitch" in response.lower()
    assert "key lessons" in response.lower()

